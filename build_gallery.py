"""
Gallery builder.

  image/gallery/_inbox/<album>/   <- drop ORIGINAL photos here (jpg, png, heic ...)
  image/gallery/<album>/          <- optimized copies (max 2000px JPG) go here
  gallery-data.js                 <- generated list the website reads

Album folder names:  YYYY-MM-name   ->  chip label "Name YYYY.MM"
                     (e.g. 2026-10-manado -> "Manado 2026.10")
Folders without a date prefix (e.g. archive) are listed last, as "Archive".
Newest albums come first. Photos inside an album are sorted by the time they
were taken (EXIF, kept in the optimized copies). To override, list filenames,
one per line, in <album>/_order.txt (unlisted files follow in time order).

Run:  python build_gallery.py
"""
import re
from pathlib import Path

from PIL import Image, ImageOps

try:
    import pillow_heif
    pillow_heif.register_heif_opener()
except ImportError:
    pass

ROOT = Path(__file__).resolve().parent
GALLERY = ROOT / 'image' / 'gallery'
INBOX = GALLERY / '_inbox'
OUT = ROOT / 'gallery-data.js'
EXTS = {'.jpg', '.jpeg', '.png', '.webp'}
SRC_EXTS = EXTS | {'.heic', '.heif'}
MAX_EDGE = 2000
QUALITY = 85


def taken_at(im):
    """Capture time 'YYYY:MM:DD HH:MM:SS' from EXIF, or ''."""
    ex = im.getexif()
    return ex.get_ifd(0x8769).get(36867) or ex.get(306) or ''


def optimize_inbox():
    if not INBOX.is_dir():
        return
    for album_in in sorted(p for p in INBOX.iterdir() if p.is_dir()):
        dest = GALLERY / album_in.name
        dest.mkdir(exist_ok=True)
        for src in sorted(album_in.iterdir()):
            if src.suffix.lower() not in SRC_EXTS:
                continue
            out = dest / (src.stem.lower() + '.jpg')
            if out.exists():
                continue
            with Image.open(src) as im:
                taken = taken_at(im)
                im = ImageOps.exif_transpose(im).convert('RGB')
                im.thumbnail((MAX_EDGE, MAX_EDGE), Image.LANCZOS)
                exif = Image.Exif()
                if taken:
                    exif[306] = taken  # DateTime
                im.save(out, 'JPEG', quality=QUALITY, optimize=True, progressive=True,
                        exif=exif)
            print(f'  optimized {album_in.name}/{src.name} -> {out.stat().st_size // 1024} KB')


def album_label(folder):
    m = re.match(r'^(\d{4})(?:-(\d{2}))?-(.+)$', folder)
    if not m:
        return folder.replace('-', ' ').replace('_', ' ').title()
    year, month, name = m.groups()
    when = f'{year}.{month}' if month else year
    return f"{name.replace('-', ' ').replace('_', ' ').title()} {when}"


def album_sort_key(folder):
    m = re.match(r'^(\d{4})(?:-(\d{2}))?-', folder)
    # dated albums newest first; undated last
    return (0, '-' + folder) if m else (1, folder)


def album_photos(folder):
    files = [p.name for p in folder.iterdir() if p.suffix.lower() in EXTS]
    order_file = folder / '_order.txt'
    ordered = []
    if order_file.exists():
        ordered = [n.strip() for n in order_file.read_text(encoding='utf-8').splitlines()
                   if n.strip() in files]
    def when(n):
        p = folder / n
        try:
            with Image.open(p) as im:
                t = taken_at(im)
        except OSError:
            t = ''
        return (t or '9999', n.lower())  # undated photos go last

    rest = sorted((n for n in files if n not in ordered), key=when)
    return ordered + rest


def build():
    optimize_inbox()
    folders = [p for p in GALLERY.iterdir() if p.is_dir() and not p.name.startswith('_')]
    folders.sort(key=lambda p: album_sort_key(p.name))
    albums, images = [], []
    for f in folders:
        photos = album_photos(f)
        if not photos:
            continue
        albums.append({'id': f.name, 'label': album_label(f.name), 'count': len(photos)})
        images += [{'src': f'image/gallery/{f.name}/{n}', 'album': f.name} for n in photos]

    def js(o):
        import json
        return json.dumps(o, ensure_ascii=False, indent=2)

    OUT.write_text(
        '/* AUTO-GENERATED by build_gallery.py - do not edit by hand */\n'
        f'const galleryAlbums = {js(albums)};\n'
        f'const galleryImages = {js(images)};\n',
        encoding='utf-8')
    print(f'gallery-data.js: {len(images)} photos in {len(albums)} albums')
    for a in albums:
        print(f"  {a['label']:<22} {a['count']}")


if __name__ == '__main__':
    build()
